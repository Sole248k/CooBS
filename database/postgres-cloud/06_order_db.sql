-- order_db: the members' shop (order-service). Written by hand; not produced by generate_seed.py.
-- Catalogue and orders only. The money stays in Oracle: an order carries the ledger's hold_id and
-- the account ids as plain numbers, with no foreign key across the two systems.
-- The three products are the ones the mobile app ships as its sample catalogue, with the same ids.

\connect order_db

CREATE TABLE IF NOT EXISTS coop_shop_product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    sku VARCHAR(64) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(50) NOT NULL,
    unit VARCHAR(80) NOT NULL,
    price NUMERIC(18, 4) NOT NULL,
    original_price NUMERIC(18, 4),
    badge VARCHAR(50),
    farm_source VARCHAR(255),
    stock_quantity INT NOT NULL DEFAULT 999,
    is_active INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS coop_shop_order (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    reference_no VARCHAR(64) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    source_account_id BIGINT NOT NULL,
    destination_account_id BIGINT,
    hold_id BIGINT,
    stage VARCHAR(30) NOT NULL DEFAULT 'HELD',
    total_amount NUMERIC(18, 4) NOT NULL,
    pickup_branch VARCHAR(150) NOT NULL DEFAULT 'PureSilver Central Mall Depot',
    pickup_pass_token VARCHAR(128) NOT NULL,
    pickup_time_slot VARCHAR(100) NOT NULL DEFAULT '4:00 PM - 6:00 PM',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_coop_order_customer ON coop_shop_order(customer_id);
CREATE INDEX IF NOT EXISTS idx_coop_order_stage ON coop_shop_order(stage);

CREATE TABLE IF NOT EXISTS coop_shop_order_item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES coop_shop_order(order_id) ON DELETE CASCADE,
    product_id BIGINT,
    product_name VARCHAR(150) NOT NULL,
    quantity INT NOT NULL,
    unit_price NUMERIC(18, 4) NOT NULL,
    subtotal NUMERIC(18, 4) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_coop_item_order ON coop_shop_order_item(order_id);

